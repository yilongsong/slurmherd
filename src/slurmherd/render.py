def walltime_warning(res: Resources, site: Site) -> Optional[str]:
    """Warn when a requested walltime exceeds the partition's known limit."""
    if not res.time or not res.partition:
        return None
    info = site.partitions.get(res.partition)
    if not info or not info.max_time:
        return None
    requested = parse_walltime(res.time)
    allowed = parse_walltime(info.max_time)
    if requested is None or allowed is None or requested <= allowed:
        return None
    return (
        f"partition {res.partition!r} allows at most {info.max_time} "
        f"but {format_walltime(requested)} was requested -- SLURM will reject this job"
    )
